
from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

from sklearn.model_selection import StratifiedGroupKFold


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Prepare stratified, group-aware dataset splits."
    )
    parser.add_argument(
        "--report",
        type=Path,
        default=Path("model/reports/inspection_report.json"),
        help="Inspection report generated by inspect.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("model/splits"),
        help="Directory where CSV split files will be saved.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducible splits.",
    )
    return parser.parse_args()


def load_report(report_path: Path) -> dict:
    if not report_path.is_file():
        raise FileNotFoundError(f"Inspection report not found: {report_path}")

    with report_path.open(encoding="utf-8") as file:
        report = json.load(file)

    if not report.get("images"):
        raise ValueError("The inspection report contains no valid images.")

    return report


def validate_duplicates(records: list[dict]) -> None:
    """Reject exact duplicates assigned to different classes."""
    classes_by_hash = defaultdict(set)

    for record in records:
        classes_by_hash[record["sha256"]].add(record["class"])

    conflicting = {
        image_hash: classes
        for image_hash, classes in classes_by_hash.items()
        if len(classes) > 1
    }

    if conflicting:
        examples = list(conflicting.items())[:5]
        raise ValueError(
            "Exact duplicate images found with conflicting class labels. "
            f"Review these hashes before splitting: {examples}"
        )


def create_groups(records: list[dict]) -> list[str]:
    """Use SHA-256 as the group identifier."""
    return [record["sha256"] for record in records]


def split_dataset(
    records: list[dict],
    seed: int,
) -> dict[str, list[int]]:
    labels = [record["class"] for record in records]
    groups = create_groups(records)
    indices = list(range(len(records)))

    splitter = StratifiedGroupKFold(
        n_splits=20,
        shuffle=True,
        random_state=seed,
    )

    # Each test index returned by the splitter represents one fold.
    folds = [
        test_indices.tolist()
        for _, test_indices in splitter.split(indices, labels, groups)
    ]

    if len(folds) != 20:
        raise RuntimeError(
            f"Expected 20 folds, received {len(folds)}."
        )

    splits = {
        "train": [
            index
            for fold in folds[:14]
            for index in fold
        ],
        "validation": [
            index
            for fold in folds[14:17]
            for index in fold
        ],
        "test": [
            index
            for fold in folds[17:20]
            for index in fold
        ],
    }

    return splits


def validate_splits(
    records: list[dict],
    splits: dict[str, list[int]],
) -> None:
    hashes_by_split = {
        name: {
            records[index]["sha256"]
            for index in indices
        }
        for name, indices in splits.items()
    }

    names = list(hashes_by_split)

    for i, first in enumerate(names):
        for second in names[i + 1:]:
            overlap = hashes_by_split[first] & hashes_by_split[second]

            if overlap:
                raise RuntimeError(
                    f"Data leakage detected between {first} and {second}: "
                    f"{len(overlap)} duplicate hashes."
                )

    all_indices = [
        index
        for indices in splits.values()
        for index in indices
    ]

    if len(all_indices) != len(records):
        raise RuntimeError(
            "Some images are missing or appear in multiple partitions."
        )

    if len(set(all_indices)) != len(records):
        raise RuntimeError("An image appears in more than one partition.")


def save_splits(
    records: list[dict],
    splits: dict[str, list[int]],
    output_dir: Path,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)

    for split_name, indices in splits.items():
        output_path = output_dir / f"{split_name}.csv"

        with output_path.open(
            "w",
            encoding="utf-8",
            newline="",
        ) as file:
            writer = csv.DictWriter(
                file,
                fieldnames=["path", "class", "sha256"],
            )
            writer.writeheader()

            for index in indices:
                record = records[index]
                writer.writerow({
                    "path": record["path"],
                    "class": record["class"],
                    "sha256": record["sha256"],
                })


def build_summary(
    records: list[dict],
    splits: dict[str, list[int]],
) -> dict:
    total = len(records)
    summary = {}

    for split_name, indices in splits.items():
        counts = Counter(records[i]["class"] for i in indices)

        summary[split_name] = {
            "num_images": len(indices),
            "percentage": round(len(indices) / total * 100, 2),
            "class_distribution": dict(sorted(counts.items())),
        }

    summary["total"] = {
        "num_images": total,
        "num_classes": len({record["class"] for record in records}),
    }

    return summary


def main() -> None:
    args = parse_args()
    report_path = args.report.expanduser().resolve()
    output_dir = args.output_dir.expanduser().resolve()

    report = load_report(report_path)
    records = report["images"]

    validate_duplicates(records)

    print(f"Preparing {len(records)} images...")
    splits = split_dataset(records, args.seed)

    validate_splits(records, splits)
    save_splits(records, splits, output_dir)

    summary = build_summary(records, splits)

    summary_path = output_dir / "split_summary.json"
    summary_path.write_text(
        json.dumps(summary, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print("\nDataset preparation completed.")

    for split_name in ("train", "validation", "test"):
        info = summary[split_name]
        print(
            f"{split_name.capitalize():12} "
            f"{info['num_images']:4} images "
            f"({info['percentage']}%)"
        )

    print(f"\nSummary: {summary_path}")
    print(f"CSV files: {output_dir}")


if __name__ == "__main__":
    main()
